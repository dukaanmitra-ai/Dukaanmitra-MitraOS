create extension if not exists "pgcrypto";

-- ------------------------------------------------------------
-- 1. Waitlist leads
--    Written by the public site using the anon key.
--    Readable only by you (service role / dashboard).
-- ------------------------------------------------------------
create table if not exists public.waitlist (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  business_type text,
  city          text,
  whatsapp      text not null,
  source        text not null default 'website',
  created_at    timestamptz not null default now()
);

comment on table public.waitlist is 'Beta signups from the DukaanMitra presentation site.';

create index if not exists waitlist_created_at_idx
  on public.waitlist (created_at desc);

create index if not exists waitlist_city_idx
  on public.waitlist (city);

alter table public.waitlist enable row level security;

-- Anyone may insert a lead. No select/update/delete policy is created,
-- so the anon key cannot read other people's numbers.
drop policy if exists "anon can join waitlist" on public.waitlist;
create policy "anon can join waitlist"
  on public.waitlist
  for insert
  to anon, authenticated
  with check (
    length(trim(name)) between 1 and 120
    and length(trim(whatsapp)) between 6 and 24
    and length(coalesce(city, '')) <= 120
    and length(coalesce(business_type, '')) <= 120
    and length(coalesce(source, '')) <= 60
  );

-- ------------------------------------------------------------
-- 2. AI chat log (optional, written by the edge function)
--    Only the edge function's service-role key can touch it.
--    No RLS policies = no public access at all.
-- ------------------------------------------------------------
create table if not exists public.ai_chats (
  id         bigint generated by default as identity primary key,
  city       text not null,
  messages   jsonb not null default '[]'::jsonb,
  reply      text,
  created_at timestamptz not null default now()
);

comment on table public.ai_chats is 'Optional transcript log for the demo chat edge function.';

create index if not exists ai_chats_created_at_idx
  on public.ai_chats (created_at desc);

alter table public.ai_chats enable row level security;

-- No policies on purpose: only the service role bypasses RLS.

-- ------------------------------------------------------------
-- 3. Handy views for the dashboard
-- ------------------------------------------------------------
-- security_invoker makes the view respect the caller's RLS on waitlist.
-- Without it, a view owned by postgres would bypass RLS and could leak
-- every phone number to the anon key.
create or replace view public.waitlist_summary
with (security_invoker = true) as
select
  date_trunc('day', created_at) as day,
  city,
  business_type,
  count(*) as leads
from public.waitlist
group by 1, 2, 3
order by 1 desc;

revoke all on public.waitlist_summary from anon, authenticated;
